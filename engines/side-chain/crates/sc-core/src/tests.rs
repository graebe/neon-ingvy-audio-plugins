#[test]
fn depth_zero_is_a_bit_exact_bypass() {
    /* No special case in the code: the product collapses to exactly 1.0 and
     * multiplying by exactly 1.0 is the identity in IEEE 754. This is the test
     * that says so out loud. */
    let sr = 48000.0;
    let mut p = Instance::new(sr);
    p.set_param("depth", "0");
    p.set_param("source", "MIDI");
    p.on_midi(&note_on(1, 36, 127), 0);

    let input: Vec<f32> = (0..512)
        .map(|i| ((i as f32) * 0.017).sin() * 0.7 + 1e-30)
        .collect();
    let mut buf = input.clone();
    p.process_f32(&mut buf, 256, None);
    assert_eq!(buf, input, "depth 0 changed a sample");
}

