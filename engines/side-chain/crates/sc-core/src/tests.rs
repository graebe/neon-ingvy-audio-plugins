/// Drive `frames` of silence-shaped audio with a transport advancing as a host
/// would, in blocks, and report how many triggers fired.
fn run_transport(p: &mut Instance, bpm: f64, sr: f64, blocks: usize, frames: usize) -> u32 {
    let start = p.fires();
    let mut buf = vec![0.0f32; frames * 2];
    let samples_per_beat = 60.0 / bpm * sr;
    let mut beats = 0.0;
    for _ in 0..blocks {
        let t = Transport {
            running: true,
            beats,
            bpm: bpm as f32,
        };
        p.process_f32(&mut buf, frames, Some(&t));
        beats += frames as f64 / samples_per_beat;
    }
    p.fires().wrapping_sub(start)
}

#[test]
fn the_cycle_fires_once_per_division() {
    let sr = 48000.0;
    /* 120 bpm, 1/4 -> one cycle per beat -> 24000 samples. 100 blocks of 480
     * is exactly two beats, so exactly two triggers. */
    let mut p = Instance::new(sr);
    p.set_param("rate", "1/4");
    assert_eq!(run_transport(&mut p, 120.0, sr, 100, 480), 2);

    /* 1/8 doubles it. */
    let mut p = Instance::new(sr);
    p.set_param("rate", "1/8");
    assert_eq!(run_transport(&mut p, 120.0, sr, 100, 480), 4);
}

