/*!
Whole-engine tests, and the helpers the per-module tests share.

WHERE THE REST LIVE. Each module carries its own tests beside it --
`shape/tests.rs` (the curve algebra and the stage machine), `follower/tests.rs`
(the detector's edge logic), `midi/tests.rs` (what a note means) and
`params/tests.rs` (the clamps and both doors). What is here drives the real
`Instance` through a transport, a MIDI queue or a key buffer, because those are
properties of the parts together rather than of any one of them.

The DSP's actual output is pinned elsewhere and deliberately not here: the curve
tables are generated by this engine and checked against it from C and from
JavaScript independently (`tests/sc_shape`, `ui/test/shape.test.mjs`), and the
envelope is MEASURED by driving the real thing with DC rather than transcribed
from the model it is supposed to be verifying.
*/

