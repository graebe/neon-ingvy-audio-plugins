/// Every curve, for the property tests that must hold for each of them.
pub(crate) const CURVES: [Curve; 3] = [Curve::Linear, Curve::Exp, Curve::SCurve];

pub(crate) fn note_on(ch: u8, note: u8, vel: u8) -> [u8; 3] {
    [0x90 | (ch - 1), note, vel]
}
/// One drum-shaped hit: a fast rise, a decay, then silence.
pub(crate) fn hit(out: &mut Vec<f32>, peak: f32, len: usize, gap: usize) {
    for i in 0..len {
        let e = 1.0 - (i as f32 / len as f32);
        out.push(peak * e * e);
    }
    out.extend(std::iter::repeat(0.0).take(gap));
}

pub(crate) fn note_off(ch: u8, note: u8) -> [u8; 3] {
    [0x80 | (ch - 1), note, 0]
}

